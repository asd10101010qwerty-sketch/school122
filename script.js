function feedFixDays() {
  let prev = '';
  document.querySelectorAll('#feedPosts .post-wrap').forEach(w => {
    w.querySelector('.feed__day').hidden = w.dataset.day === prev;
    prev = w.dataset.day;
  });
}

// Insert new posts in id order, re-render changed ones (views, edits). Returns how many were new.
function feedUpsert(list) {
  const box = document.getElementById('feedPosts');
  let added = 0;
  list.forEach(p => {
    const sig = JSON.stringify(p);
    const old = feed.posts.get(p.id);
    if (old && old.sig === sig) return;
    if (old) {
      const cur = feed.nodes.get(p.id);
      if ([...cur.querySelectorAll('video')].some(v => !v.paused)) return; // don't interrupt a playing video
      const node = renderPost(p);
      cur.replaceWith(node);
      feed.nodes.set(p.id, node);
    } else {
      const node = renderPost(p);
      const next = [...feed.nodes.keys()].filter(id => id > p.id).sort((a, b) => a - b)[0];
      box.insertBefore(node, next ? feed.nodes.get(next) : null);
      feed.nodes.set(p.id, node);
      added++;
    }
    feed.posts.set(p.id, { sig, post: p });
  });
  feedFixDays();
  return added;
}

