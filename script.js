function tkParts(date) {
  const p = {};
  new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Tashkent', year: 'numeric', month: 'numeric', day: 'numeric', hour: '2-digit', minute: '2-digit', hour12: false })
    .formatToParts(date).forEach(x => { p[x.type] = x.value; });
  return { y: +p.year, m: +p.month, d: +p.day, time: `${p.hour === '24' ? '00' : p.hour}:${p.minute}`, key: `${p.year}-${p.month}-${p.day}` };
}
function dayLabel(iso) {
  const t = FEED_TXT[feed.lang], d = tkParts(new Date(iso));
  if (d.key === tkParts(new Date()).key) return t.today;
  if (d.key === tkParts(new Date(Date.now() - 864e5)).key) return t.yesterday;
  const s = t.day(d.d, t.months[d.m - 1]);
  return d.y === tkParts(new Date()).y ? s : `${s} ${d.y}`;
}

function el(tag, cls, html) { const e = document.createElement(tag); if (cls) e.className = cls; if (html != null) e.innerHTML = html; return e; }
function attr(s) { return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;'); }

function renderPost(p) {
  const t = FEED_TXT[feed.lang];
  const wrap = el('div', 'post-wrap');
  wrap.dataset.id = p.id;
  wrap.dataset.day = p.date ? tkParts(new Date(p.date)).key : '';
  wrap.appendChild(el('div', 'feed__day', `<span>${p.date ? dayLabel(p.date) : ''}</span>`));
  const art = el('article', 'post');
  if (p.media.length) {
    const n = p.media.length;
    const grid = el('div', `post__media post__media--${Math.min(n, 3)}${n > 1 && n % 2 ? ' post__media--odd' : ''}`);
    p.media.forEach(m => {
      if (m.type === 'photo') {
        grid.insertAdjacentHTML('beforeend', `<button class="post__photo" data-src="${attr(m.src)}" aria-label="Photo"><img src="${attr(m.src)}" alt="" loading="lazy"></button>`);
      } else if (m.src) {
        grid.insertAdjacentHTML('beforeend', `<div class="post__video"><video src="${attr(m.src)}"${m.thumb ? ` poster="${attr(m.thumb)}"` : ''} controls playsinline preload="none"></video></div>`);
      } else {
        grid.insertAdjacentHTML('beforeend', `<a class="post__vthumb" href="${attr(p.url)}" target="_blank" rel="noopener">${m.thumb ? `<img src="${attr(m.thumb)}" alt="" loading="lazy">` : ''}<span class="post__play"><svg class="ico"><use href="#i-play"/></svg></span><small>${t.watch}</small></a>`);
      }
    });
    art.appendChild(grid);
  }
  if (p.text) {
    const tx = el('div', 'post__text', p.text);
    art.appendChild(tx);
    if (p.text.length > 700) {
      tx.classList.add('post__text--clamp');
      const b = el('button', 'post__more', t.more);
      b.addEventListener('click', () => {
        const c = tx.classList.toggle('post__text--clamp');
        b.textContent = c ? FEED_TXT[feed.lang].more : FEED_TXT[feed.lang].less;
      });
      art.appendChild(b);
    }
  }
  const time = p.date ? tkParts(new Date(p.date)).time : '';
  art.appendChild(el('div', 'post__meta',
    (p.views ? `<span><svg class="ico"><use href="#i-eye"/></svg>${attr(p.views)}</span>` : '') +
    `<a href="${attr(p.url)}" target="_blank" rel="noopener" title="${t.open}">${time}<svg class="ico"><use href="#i-telegram"/></svg></a>`));
  wrap.appendChild(art);
  return wrap;
}

