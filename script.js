const TITLES = {
  uz: '122-maktab — Yunusobod tumani',
  ru: 'Школа № 122 — Юнусабадский район',
  en: 'School No. 122 — Yunusabad district',
};

const nodes = document.querySelectorAll('[data-i18n]');
T.uz = {};
nodes.forEach(el => { T.uz[el.dataset.i18n] = el.textContent; });

function setLang(lang) {
  if (!T[lang]) lang = 'uz';
  nodes.forEach(el => {
    const v = T[lang][el.dataset.i18n];
    if (v) el.textContent = v;
  });
  document.documentElement.lang = lang;
  document.title = TITLES[lang];
  document.querySelectorAll('.lang button').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  localStorage.setItem('lang', lang);
}

document.querySelectorAll('.lang button').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));
setLang(localStorage.getItem('lang') || 'uz');

// Theme
document.getElementById('themeToggle').addEventListener('click', () => {
  const next = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-theme', next);
  localStorage.setItem('theme', next);
});

// Mobile menu
const nav = document.getElementById('nav');
document.getElementById('burger').addEventListener('click', () => nav.classList.toggle('open'));
nav.querySelectorAll('a').forEach(a => a.addEventListener('click', () => nav.classList.remove('open')));

// Lightbox
const lb = document.getElementById('lightbox');
const lbImg = document.getElementById('lbImg');
document.querySelectorAll('.gallery__item').forEach(btn => btn.addEventListener('click', () => {
  lbImg.src = btn.querySelector('img').src;
  lb.hidden = false;
}));
lb.addEventListener('click', e => { if (e.target !== lbImg) lb.hidden = true; });
document.addEventListener('keydown', e => { if (e.key === 'Escape') lb.hidden = true; });

// Reveal on scroll
const io = new IntersectionObserver(entries => entries.forEach(en => {
  if (en.isIntersecting) { en.target.classList.add('visible'); io.unobserve(en.target); }
}), { threshold: 0.12 });
document.querySelectorAll('.section__head, .about__media, .about__text, .card, .news__item, .gallery__item, .contact__info, .contact__map, .value')
  .forEach(el => { el.classList.add('reveal'); io.observe(el); });

document.getElementById('year').textContent = new Date().getFullYear();
